function h1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 300, after: 160 },
    children: [font(16, { bold: true, color: BLUE, text })] });
}
function h2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 220, after: 120 },
    children: [font(13, { bold: true, color: '333333', text })] });
}
function p(text, opts = {}) {
  return new Paragraph({ spacing: { before: 60, after: 60, line: 320 }, children: [font(10.5, { text, ...opts })] });
}
function bullets(items) {
  return items.map(t => new Paragraph({ bullet: { level: 0 }, spacing: { before: 40, after: 40 },
    children: [font(10.5, { text: t })] }));
}
function riskBox(title, text) {
  return new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, borders: BORDERS, rows: [
    new TableRow({ children: [new TableCell({
      shading: { type: ShadingType.CLEAR, fill: 'FCE4E4' },
      margins: { top: 120, bottom: 120, left: 200, right: 200 },
      children: [
        new Paragraph({ children: [font(11, { bold: true, color: RED, text: '⚠ ' + title })] }),
        new Paragraph({ spacing: { before: 60 }, children: [font(10.5, { text })] })
      ] })] })
  ] });
}
function mkTable(header, rows, colWidths, opts = {}) {
  const total = colWidths.reduce((a, b) => a + b, 0);
  const hdrRow = new TableRow({ tableHeader: true, children: header.map((t, i) => new TableCell({
    shading: { type: ShadingType.CLEAR, fill: BLUE },
    width: { size: colWidths[i] / total * 100, type: WidthType.PERCENTAGE },
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [font(10, { bold: true, color: 'FFFFFF', text: t })] })] })) });
  const bodyRows = rows.map((r, ri) => new TableRow({ children: r.map((t, i) => new TableCell({
    shading: { type: ShadingType.CLEAR, fill: ri % 2 === 1 ? GRAY : 'FFFFFF' },
    width: { size: colWidths[i] / total * 100, type: WidthType.PERCENTAGE },
    margins: { top: 50, bottom: 50, left: 80, right: 80 },
    children: [new Paragraph({
      alignment: (opts.centerCols || []).includes(i) ? AlignmentType.CENTER : AlignmentType.LEFT,
      children: [font(9.5, { text: String(t) })] })] })) }));
  return new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, borders: BORDERS, rows: [hdrRow, ...bodyRows] });
}

