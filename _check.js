function norm(s){
  return (s||'').replace(/[\uFF01-\uFF5E]/g, ch=>String.fromCharCode(ch.charCodeAt(0)-0xFEE0))
    .replace(/\u3000/g,' ').replace(/\s+/g,'').toUpperCase();
}

